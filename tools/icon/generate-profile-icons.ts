// Generates the profile icons for Android (vector drawables + an id → drawable map) and the
// dashboard (path data) from design/icons/profile-icons.json. Run: npm run profile-icons
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = JSON.parse(readFileSync(join(root, 'design/icons/profile-icons.json'), 'utf8')) as {
  viewBox: number;
  strokeWidth: number;
  icons: Record<string, string[]>;
};
const ids = Object.keys(source.icons);
const header = 'Generated by tools/icon/generate-profile-icons.ts from design/icons/profile-icons.json. Do not edit.';
const resName = (id: string) => `profile_icon_${id}`;

// Android: white strokes, tinted where used (Icon(tint = …)).
const drawables = join(root, 'android/app/src/main/res/drawable');
for (const [id, paths] of Object.entries(source.icons)) {
  const body = paths
    .map(
      (d) => `    <path
        android:pathData="${d}"
        android:strokeWidth="${source.strokeWidth}"
        android:strokeColor="#FFFFFFFF"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`,
    )
    .join('\n');
  writeFileSync(
    join(drawables, `${resName(id)}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- ${header} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="${source.viewBox}"
    android:viewportHeight="${source.viewBox}">
${body}
</vector>
`,
  );
}

const kotlinDir = join(root, 'android/app/src/main/java/gr/barlab/negroni/ui/profile');
mkdirSync(kotlinDir, { recursive: true });
writeFileSync(
  join(kotlinDir, 'ProfileIconSet.kt'),
  `// ${header}
package gr.barlab.negroni.ui.profile

import androidx.annotation.DrawableRes
import gr.barlab.negroni.R

object ProfileIconSet {
    /** Every icon id, in picker order. */
    val ids: List<String> = listOf(${ids.map((id) => `"${id}"`).join(', ')})

    @DrawableRes
    fun drawable(id: String): Int = when (id) {
${ids.map((id) => `        "${id}" -> R.drawable.${resName(id)}`).join('\n')}
        else -> R.drawable.${resName('person')}
    }
}
`,
);

writeFileSync(
  join(root, 'web/src/ui/profileIconSet.ts'),
  `// ${header}

export const ICON_VIEWBOX = ${source.viewBox};
export const ICON_STROKE = ${source.strokeWidth};

/** Every icon id → its SVG path data, in picker order. */
export const PROFILE_ICONS: Record<string, readonly string[]> = ${JSON.stringify(source.icons, null, 2)};
`,
);

console.log(`${ids.length} profile icons → Android drawables, ProfileIconSet.kt, web/src/ui/profileIconSet.ts`);
