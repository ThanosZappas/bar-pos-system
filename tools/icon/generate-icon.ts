// Generates the text launcher icon from the bundled OFL fonts (outlines, so no font is needed
// at runtime and it stays sharp at every size). Colours are the barlab.gr/menu.html tokens.
//   npm --prefix tools/icon run generate
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const BG = '#111008'; // page background
const GOLD = '#c9a84c'; // .hero-logo / prices
const CREAM = '#e8dfc8'; // body text

const root = new URL('../../', import.meta.url);
const font = (name: string) => {
  const b = readFileSync(new URL(`design/fonts/${name}`, root));
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};
const playfairBold = font('playfair_display_bold.ttf');
const latoBold = font('lato_bold.ttf');

// Adaptive icons are drawn on 108×108; launchers may mask everything outside a centred circle
// of diameter 66, so all text stays inside it.
const SIZE = 108;
const CENTER = SIZE / 2;

/**
 * SVG / VectorDrawable path data straight from the outline commands. opentype.js 2.0's own
 * toPathData drops closing segments (it broke the counters of the final "B") or flips Y.
 */
function pathData(path: opentype.Path): string {
  // 0.1 of 108 units is far below a pixel even at 192 px; shorter paths draw faster.
  const n = (v: number) => String(Math.round(v * 10) / 10);
  return path.commands
    .map((c) => {
      switch (c.type) {
        case 'M': return `M${n(c.x)} ${n(c.y)}`;
        case 'L': return `L${n(c.x)} ${n(c.y)}`;
        case 'Q': return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case 'C': return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        default: return 'Z';
      }
    })
    .join('');
}

/** Path of `text` scaled so its ink is `width` wide, horizontally centred, baseline at `baseline`. */
function line(f: opentype.Font, text: string, width: number, baseline: number, trackingEm = 0) {
  const at = (size: number, x: number) => {
    if (trackingEm === 0) return f.getPath(text, x, baseline, size);
    const path = new opentype.Path();
    let cursor = x;
    for (const g of f.stringToGlyphs(text)) {
      path.extend(g.getPath(cursor, baseline, size));
      cursor += (g.advanceWidth! / f.unitsPerEm) * size + trackingEm * size;
    }
    return path;
  };
  const probe = at(100, 0).getBoundingBox();
  const size = (100 * width) / (probe.x2 - probe.x1);
  const box = at(size, 0).getBoundingBox();
  const path = at(size, CENTER - (box.x1 + box.x2) / 2);
  return { d: pathData(path), box: path.getBoundingBox() };
}

const negroni = line(playfairBold, 'Negroni', 60, 54);
const barLab = line(latoBold, 'BAR LAB', 40, 68, 0.18);

// Sanity check: every ink corner inside the safe circle (radius 33).
for (const { box } of [negroni, barLab]) {
  for (const [x, y] of [[box.x1, box.y1], [box.x2, box.y1], [box.x1, box.y2], [box.x2, box.y2]]) {
    const r = Math.hypot(x - CENTER, y - CENTER);
    if (r > 33.5) throw new Error(`Text corner at r=${r.toFixed(1)} leaves the safe zone`);
  }
}

const res = new URL('android/app/src/main/res/', root);
const write = (path: URL, text: string) => {
  mkdirSync(new URL('.', path), { recursive: true });
  writeFileSync(path, text);
};
const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon/generate-icon.ts. Do not edit by hand. -->\n';
const vector = (fillA: string, fillB: string) =>
  `${header}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="${fillA}" android:pathData="${negroni.d}" />
    <path android:fillColor="${fillB}" android:pathData="${barLab.d}" />
</vector>
`;
const adaptive = `${header}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

write(new URL('drawable/ic_launcher_foreground.xml', res), vector(GOLD, CREAM));
// Android 13+ themed icons recolour this single-colour layer.
write(new URL('drawable/ic_launcher_monochrome.xml', res), vector('#FFFFFFFF', '#FFFFFFFF'));
write(new URL('mipmap-anydpi/ic_launcher.xml', res), adaptive);
write(new URL('mipmap-anydpi/ic_launcher_round.xml', res), adaptive);
write(new URL('values/ic_launcher_background.xml', res), `${header}<resources>\n    <color name="ic_launcher_background">${BG}</color>\n</resources>\n`);

// Dashboard favicon and a preview for review (rounded square like most launchers).
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}">
  <rect width="${SIZE}" height="${SIZE}" rx="24" fill="${BG}"/>
  <path fill="${GOLD}" d="${negroni.d}"/>
  <path fill="${CREAM}" d="${barLab.d}"/>
</svg>
`;
write(new URL('web/public/favicon.svg', root), svg);
write(new URL('design/icon/icon.svg', root), svg);
console.log('Icon written: Android adaptive + monochrome layers, web/public/favicon.svg, design/icon/icon.svg');
